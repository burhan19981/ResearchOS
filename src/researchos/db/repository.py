def create_contribution_candidate(
    session: Session,
    *,
    project_id: int,
    title: str,
    description: str,
    contribution_type: Optional[str] = None,
    planning_status: PlanningApprovalStatus = PlanningApprovalStatus.CANDIDATE,
    version: Optional[int] = None,
    supersedes_id: Optional[int] = None,
    provider: Optional[str] = None,
    model: Optional[str] = None,
    prompt_name: Optional[str] = None,
    prompt_version: Optional[str] = None,
) -> ContributionCandidate:
    """Create a contribution candidate.

    `supersedes_id`, if given, must identify an existing
    `ContributionCandidate` in this same project that is not already
    superseded by another row (the table's own `UniqueConstraint` on
    `supersedes_id` enforces the latter, raising
    `IntegrityConstraintError` on a second attempt to supersede the same
    row — an unbranching lineage). If `version` is omitted, it defaults
    to `supersedes.version + 1` when `supersedes_id` is given, else `1` —
    an independent, unrelated contribution always starts a new lineage
    at version 1, never inheriting a shared project-wide counter the way
    `MethodologyPlan.version` does.
    """
    _get_project_or_raise(session, project_id)
    supersedes: Optional[ContributionCandidate] = None
    if supersedes_id is not None:
        supersedes = session.get(ContributionCandidate, supersedes_id)
        if supersedes is None or supersedes.project_id != project_id:
            raise NotFoundError(f"ContributionCandidate {supersedes_id} does not exist in project {project_id}.")
    if version is None:
        version = (supersedes.version + 1) if supersedes is not None else 1
    contribution = ContributionCandidate(
        project_id=project_id,
        title=title,
        description=description,
        contribution_type=contribution_type,
        planning_status=planning_status,
        version=version,
        supersedes_id=supersedes_id,
        provider=provider,
        model=model,
        prompt_name=prompt_name,
        prompt_version=prompt_version,
    )
    session.add(contribution)
    _flush(session)
    return contribution


