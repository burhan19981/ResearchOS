def create_dataset_version(
    session: Session,
    *,
    project_id: int,
    dataset_record_id: int,
    version: Optional[int] = None,
    supersedes_id: Optional[int] = None,
    description: Optional[str] = None,
    source_uri: Optional[str] = None,
    format: Optional[str] = None,  # noqa: A002 - matches domain vocabulary
    sample_count: Optional[int] = None,
    split_definition: Optional[dict[str, Any]] = None,
    class_definition: Optional[list[Any]] = None,
    preprocessing_definition: Optional[dict[str, Any]] = None,
    augmentation_definition: Optional[dict[str, Any]] = None,
    content_fingerprint: Optional[str] = None,
    metadata_fingerprint: Optional[str] = None,
    lifecycle_status: DatasetLifecycleStatus = DatasetLifecycleStatus.DRAFT,
    validation_result: Optional[dict[str, Any]] = None,
    provider: Optional[str] = None,
    model: Optional[str] = None,
    prompt_name: Optional[str] = None,
    prompt_version: Optional[str] = None,
) -> DatasetVersion:
    """Create a dataset version.

    `dataset_record_id` must identify an existing `DatasetRecord` in
    this project. `supersedes_id`, if given, must identify an existing
    `DatasetVersion` in this same project AND the same
    `dataset_record_id` (a version's lineage never crosses logical
    datasets) that is not already superseded by another row (the
    table's `UniqueConstraint` on `supersedes_id` enforces the latter —
    an unbranching lineage, exactly like `ContributionCandidate`/
    `ExperimentalDesign`). If `version` is omitted, it defaults to
    `supersedes.version + 1` when `supersedes_id` is given, else `1`.
    """
    _get_project_or_raise(session, project_id)
    dataset_record = session.get(DatasetRecord, dataset_record_id)
    if dataset_record is None or dataset_record.project_id != project_id:
        raise NotFoundError(f"DatasetRecord {dataset_record_id} does not exist in project {project_id}.")
    supersedes: Optional[DatasetVersion] = None
    if supersedes_id is not None:
        supersedes = session.get(DatasetVersion, supersedes_id)
        if supersedes is None or supersedes.project_id != project_id:
            raise NotFoundError(f"DatasetVersion {supersedes_id} does not exist in project {project_id}.")
        if supersedes.dataset_record_id != dataset_record_id:
            raise NotFoundError(
                f"DatasetVersion {supersedes_id} belongs to DatasetRecord {supersedes.dataset_record_id}, "
                f"not {dataset_record_id} — a version's lineage cannot cross logical datasets."
            )
    if version is None:
        version = (supersedes.version + 1) if supersedes is not None else 1
    dataset_version = DatasetVersion(
        project_id=project_id,
        dataset_record_id=dataset_record_id,
        version=version,
        supersedes_id=supersedes_id,
        description=description,
        source_uri=source_uri,
        format=format,
        sample_count=sample_count,
        split_definition=split_definition,
        class_definition=class_definition,
        preprocessing_definition=preprocessing_definition,
        augmentation_definition=augmentation_definition,
        content_fingerprint=content_fingerprint,
        metadata_fingerprint=metadata_fingerprint,
        lifecycle_status=lifecycle_status,
        validation_result=validation_result,
        provider=provider,
        model=model,
        prompt_name=prompt_name,
        prompt_version=prompt_version,
    )
    session.add(dataset_version)
    _flush(session)
    return dataset_version


