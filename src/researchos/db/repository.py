def create_methodology_version(
    session: Session,
    *,
    project_id: int,
    description: str,
    status: MethodologyStatus = MethodologyStatus.DRAFT,
    version: Optional[int] = None,
    planning_status: PlanningApprovalStatus = PlanningApprovalStatus.CANDIDATE,
    methodology_type: Optional[str] = None,
    components: Optional[list[Any]] = None,
    assumptions: Optional[list[Any]] = None,
    risks: Optional[list[Any]] = None,
    reproducibility_requirements: Optional[str] = None,
    provider: Optional[str] = None,
    model: Optional[str] = None,
    prompt_name: Optional[str] = None,
    prompt_version: Optional[str] = None,
    contribution_candidate_id: Optional[int] = None,
    contribution_candidate_version: Optional[int] = None,
    contribution_candidate_status_at_generation: Optional[str] = None,
) -> MethodologyPlan:
    """Create a new methodology plan version for a project.

    If `version` is omitted, it is set to one greater than the highest
    existing version for this project (starting at 1), giving simple
    monotonic versioning without any workflow logic. If
    `contribution_candidate_id` is given, it must exist in this project.
    """
    _get_project_or_raise(session, project_id)
    if contribution_candidate_id is not None:
        contribution = session.get(ContributionCandidate, contribution_candidate_id)
        if contribution is None or contribution.project_id != project_id:
            raise NotFoundError(
                f"ContributionCandidate {contribution_candidate_id} does not exist in project {project_id}."
            )
    if version is None:
        current_max = session.scalar(
            select(MethodologyPlan.version)
            .where(MethodologyPlan.project_id == project_id)
            .order_by(MethodologyPlan.version.desc())
            .limit(1)
        )
        version = (current_max or 0) + 1
    plan = MethodologyPlan(
        project_id=project_id,
        description=description,
        status=status,
        version=version,
        planning_status=planning_status,
        methodology_type=methodology_type,
        components=components,
        assumptions=assumptions,
        risks=risks,
        reproducibility_requirements=reproducibility_requirements,
        provider=provider,
        model=model,
        prompt_name=prompt_name,
        prompt_version=prompt_version,
        contribution_candidate_id=contribution_candidate_id,
        contribution_candidate_version=contribution_candidate_version,
        contribution_candidate_status_at_generation=contribution_candidate_status_at_generation,
    )
    session.add(plan)
    _flush(session)
    return plan


