def _flush(session: Session) -> None:
    """Flush pending changes, translating DB integrity failures.

    Flushing (rather than committing) here means autogenerated columns
    (id, created_at, ...) are populated without ending the caller's
    transaction — commit/rollback remain the caller's responsibility
    via `session_scope()`.
    """
    try:
        session.flush()
    except IntegrityError as exc:
        session.rollback()
        detail = str(exc.orig) if exc.orig is not None else str(exc)
        raise IntegrityConstraintError(detail) from exc


def _get_project_or_raise(session: Session, project_id: int) -> ResearchProject:
    project = session.get(ResearchProject, project_id)
    if project is None:
        raise NotFoundError(f"ResearchProject {project_id} does not exist.")
    return project


def _get_experiment_or_raise(session: Session, experiment_id: int) -> Experiment:
    experiment = session.get(Experiment, experiment_id)
    if experiment is None:
        raise NotFoundError(f"Experiment {experiment_id} does not exist.")
    return experiment


def _apply_updates(obj: Any, fields: dict[str, Any]) -> None:
    for key, value in fields.items():
        if not hasattr(obj, key):
            raise ValueError(f"{type(obj).__name__} has no attribute '{key}'.")
        setattr(obj, key, value)


