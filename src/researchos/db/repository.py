def create_run(
    session: Session,
    *,
    project_id: int,
    experiment_id: int,
    timeout_seconds: int,
    experiment_specification_id: Optional[int] = None,
    dataset_version_id: Optional[int] = None,
    environment_snapshot_id: Optional[int] = None,
    execution_backend: ExecutionBackend = ExecutionBackend.LOCAL_PYTHON,
    execution_target: Optional[dict[str, Any]] = None,
    experiment_specification_version: Optional[int] = None,
    experiment_specification_status_at_execution: Optional[str] = None,
    configuration_hash: Optional[str] = None,
    configuration_snapshot: Optional[dict[str, Any]] = None,
    dataset_version_version: Optional[int] = None,
    dataset_version_status_at_execution: Optional[str] = None,
    dataset_fingerprint: Optional[str] = None,
    code_repository: Optional[str] = None,
    code_commit: Optional[str] = None,
    code_branch: Optional[str] = None,
    working_tree_clean: Optional[bool] = None,
    code_provenance_unavailable_reason: Optional[str] = None,
    seed: Optional[int] = None,
) -> Run:
    """Create one `Run` row in `RunStatus.CREATED`.

    Validates that `experiment_id` and (if given)
    `experiment_specification_id` / `dataset_version_id` all exist and
    belong to `project_id` — never silently mixed across projects.
    `environment_snapshot_id`, if given, must exist (it is
    intentionally not project-scoped; see `EnvironmentSnapshot`'s
    docstring).

    This is a low-level persistence primitive only: it does NOT check
    upstream approval status, does NOT run preflight, and does NOT
    require execution approval — see
    `researchos.execution.orchestrator.request_run()` for the full,
    validated entry point every real caller should use instead.
    """
    _get_project_or_raise(session, project_id)
    experiment = session.get(Experiment, experiment_id)
    if experiment is None or experiment.project_id != project_id:
        raise NotFoundError(f"Experiment {experiment_id} does not exist in project {project_id}.")
    if experiment_specification_id is not None:
        spec = session.get(ExperimentSpecification, experiment_specification_id)
        if spec is None or spec.project_id != project_id:
            raise NotFoundError(
                f"ExperimentSpecification {experiment_specification_id} does not exist in project {project_id}."
            )
    if dataset_version_id is not None:
        dataset_version = session.get(DatasetVersion, dataset_version_id)
        if dataset_version is None or dataset_version.project_id != project_id:
            raise NotFoundError(f"DatasetVersion {dataset_version_id} does not exist in project {project_id}.")
    if environment_snapshot_id is not None:
        snapshot = session.get(EnvironmentSnapshot, environment_snapshot_id)
        if snapshot is None:
            raise NotFoundError(f"EnvironmentSnapshot {environment_snapshot_id} does not exist.")
    run = Run(
        project_id=project_id,
        experiment_id=experiment_id,
        experiment_specification_id=experiment_specification_id,
        dataset_version_id=dataset_version_id,
        environment_snapshot_id=environment_snapshot_id,
        status=RunStatus.CREATED,
        execution_backend=execution_backend,
        execution_target=execution_target,
        experiment_specification_version=experiment_specification_version,
        experiment_specification_status_at_execution=experiment_specification_status_at_execution,
        configuration_hash=configuration_hash,
        configuration_snapshot=configuration_snapshot,
        dataset_version_version=dataset_version_version,
        dataset_version_status_at_execution=dataset_version_status_at_execution,
        dataset_fingerprint=dataset_fingerprint,
        code_repository=code_repository,
        code_commit=code_commit,
        code_branch=code_branch,
        working_tree_clean=working_tree_clean,
        code_provenance_unavailable_reason=code_provenance_unavailable_reason,
        seed=seed,
        timeout_seconds=timeout_seconds,
    )
    session.add(run)
    _flush(session)
    return run


def get_run(session: Session, run_id: int) -> Optional[Run]:
    return session.get(Run, run_id)


