_EVIDENCE_SUBJECT_MODELS: dict[EvidenceSubjectType, type] = {
    EvidenceSubjectType.ANALYSIS_CLAIM: AnalysisClaim,
    EvidenceSubjectType.GAP_CANDIDATE: ResearchGap,
    EvidenceSubjectType.NOVELTY_ASSESSMENT: NoveltyAssessment,
    EvidenceSubjectType.NOVELTY_COMPARISON: NoveltyComparison,
    # --- Added in Phase 7 (researchos.planning) ---
    EvidenceSubjectType.RESEARCH_QUESTION: ResearchQuestion,
    EvidenceSubjectType.CONTRIBUTION_CANDIDATE: ContributionCandidate,
    EvidenceSubjectType.METHODOLOGY_PLAN: MethodologyPlan,
    EvidenceSubjectType.DATASET_REQUIREMENTS: DatasetRequirements,
    EvidenceSubjectType.EXPERIMENTAL_DESIGN: ExperimentalDesign,
    # --- Added in Phase 8A (researchos.specification) ---
    EvidenceSubjectType.DATASET_VERSION: DatasetVersion,
    EvidenceSubjectType.EXPERIMENT_SPECIFICATION: ExperimentSpecification,
    # --- Added in Phase 8 (researchos.analysis) ---
    EvidenceSubjectType.SCIENTIFIC_CLAIM: ScientificClaim,
    EvidenceSubjectType.ANALYSIS_RECORD: AnalysisRecord,
}

# The AnalysisInput analogue of _EVIDENCE_SUBJECT_MODELS — same
# polymorphic-by-convention pattern, a separate dict because
# AnalysisInput's vocabulary (RUN/METRIC/ARTIFACT) is its own, distinct
# from EvidenceSubjectType's.
_ANALYSIS_INPUT_MODELS: dict[AnalysisInputType, type] = {
    AnalysisInputType.RUN: Run,
    AnalysisInputType.METRIC: Metric,
    AnalysisInputType.ARTIFACT: ArtifactMetadata,
}


def create_evidence_link(
    session: Session,
    *,
    project_id: int,
    literature_item_id: int,
    subject_type: EvidenceSubjectType,
    subject_id: int,
    relationship_type: EvidenceRelationship = EvidenceRelationship.CITES,
) -> EvidenceLink:
    """Record one traceable evidence relationship.

    Validates that `literature_item_id` and the polymorphic
    `(subject_type, subject_id)` both actually exist in this project
    before inserting — `subject_id` cannot be a database foreign key
    since it points into different tables depending on `subject_type`.
    """
    _get_project_or_raise(session, project_id)
    if session.get(LiteratureItem, literature_item_id) is None:
        raise NotFoundError(f"LiteratureItem {literature_item_id} does not exist.")
    subject_model = _EVIDENCE_SUBJECT_MODELS[subject_type]
    subject = session.get(subject_model, subject_id)
    if subject is None or getattr(subject, "project_id", None) != project_id:
        raise NotFoundError(f"{subject_type.value} {subject_id} does not exist in project {project_id}.")

    link = EvidenceLink(
        project_id=project_id,
        literature_item_id=literature_item_id,
        subject_type=subject_type,
        subject_id=subject_id,
        relationship_type=relationship_type,
    )
    session.add(link)
    _flush(session)
    return link


def list_evidence_links(
    session: Session,
    project_id: int,
    *,
    subject_type: Optional[EvidenceSubjectType] = None,
    subject_id: Optional[int] = None,
    literature_item_id: Optional[int] = None,
) -> list[EvidenceLink]:
    stmt = select(EvidenceLink).where(EvidenceLink.project_id == project_id)
    if subject_type is not None:
        stmt = stmt.where(EvidenceLink.subject_type == subject_type)
    if subject_id is not None:
        stmt = stmt.where(EvidenceLink.subject_id == subject_id)
    if literature_item_id is not None:
        stmt = stmt.where(EvidenceLink.literature_item_id == literature_item_id)
    stmt = stmt.order_by(EvidenceLink.id)
    return list(session.scalars(stmt))


