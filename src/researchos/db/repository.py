def create_project(
    session: Session,
    *,
    title: str,
    description: Optional[str] = None,
    field: Optional[str] = None,
    status: ProjectStatus = ProjectStatus.ACTIVE,
    current_stage: Optional[str] = None,
) -> ResearchProject:
    project = ResearchProject(
        title=title,
        description=description,
        field=field,
        status=status,
        current_stage=current_stage,
    )
    session.add(project)
    _flush(session)
    return project


def get_project(session: Session, project_id: int) -> Optional[ResearchProject]:
    return session.get(ResearchProject, project_id)


def update_project(session: Session, project_id: int, **fields: Any) -> ResearchProject:
    project = _get_project_or_raise(session, project_id)
    _apply_updates(project, fields)
    _flush(session)
    return project


def list_projects(
    session: Session, *, status: Optional[ProjectStatus] = None
) -> list[ResearchProject]:
    stmt = select(ResearchProject).order_by(ResearchProject.id)
    if status is not None:
        stmt = stmt.where(ResearchProject.status == status)
    return list(session.scalars(stmt))


