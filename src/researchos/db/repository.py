"""Repository layer: persistence operations for ResearchOS research state.

Every function here takes an explicit `Session` supplied by the caller
and never commits — only `flush()`es, so autogenerated ids/timestamps
are populated and integrity errors surface immediately. Wrap one or
more calls in `researchos.db.engine.session_scope()` to get atomic
commit-or-rollback:

```python
from researchos.db import repository
from researchos.db.engine import session_scope

with session_scope() as session:
    project = repository.create_project(session, title="My Project")
    repository.append_audit_event(
        session, project_id=project.id, event_type="project_created", actor="system"
    )
# both committed together, or both rolled back together on any error
```

These are persistence operations only — no workflow decisions, no LLM
calls, no business/orchestration logic beyond the existence checks and
validation already enforced on the models themselves. In particular,
"does this id exist, and does it belong to the given project" is
checked here (functions that accept a `project_id` alongside a related
id validate both together), but both failure cases raise the same
`NotFoundError` — this layer is intentionally not the place that
distinguishes "missing" from "wrong project" for a caller; see
`researchos.db.errors.NotFoundError`'s docstring for why, and
`researchos.planning.orchestration` for the higher layer that does draw
that distinction with its own typed errors.
"""

