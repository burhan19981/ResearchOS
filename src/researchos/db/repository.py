def link_contribution_candidate_question(
    session: Session,
    *,
    project_id: int,
    contribution_candidate_id: int,
    research_question_id: int,
) -> ContributionCandidateQuestion:
    """Record one (contribution, research question) traceability edge.

    Validates that both endpoints exist and belong to `project_id` —
    never silently links across projects. A duplicate pair is rejected
    by the table's own uniqueness constraint (surfaces as
    `IntegrityConstraintError`).
    """
    _get_project_or_raise(session, project_id)
    contribution = session.get(ContributionCandidate, contribution_candidate_id)
    if contribution is None or contribution.project_id != project_id:
        raise NotFoundError(f"ContributionCandidate {contribution_candidate_id} does not exist in project {project_id}.")
    question = session.get(ResearchQuestion, research_question_id)
    if question is None or question.project_id != project_id:
        raise NotFoundError(f"ResearchQuestion {research_question_id} does not exist in project {project_id}.")
    link = ContributionCandidateQuestion(
        project_id=project_id,
        contribution_candidate_id=contribution_candidate_id,
        research_question_id=research_question_id,
    )
    session.add(link)
    _flush(session)
    return link


def list_contribution_candidate_questions(
    session: Session,
    project_id: int,
    *,
    contribution_candidate_id: Optional[int] = None,
    research_question_id: Optional[int] = None,
) -> list[ContributionCandidateQuestion]:
    stmt = select(ContributionCandidateQuestion).where(ContributionCandidateQuestion.project_id == project_id)
    if contribution_candidate_id is not None:
        stmt = stmt.where(ContributionCandidateQuestion.contribution_candidate_id == contribution_candidate_id)
    if research_question_id is not None:
        stmt = stmt.where(ContributionCandidateQuestion.research_question_id == research_question_id)
    stmt = stmt.order_by(ContributionCandidateQuestion.id)
    return list(session.scalars(stmt))


