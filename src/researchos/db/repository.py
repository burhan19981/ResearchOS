def update_run_lifecycle(
    session: Session,
    run_id: int,
    *,
    expected_status: RunStatus,
    new_status: RunStatus,
    **fields: Any,
) -> Run:
    """Transition one `Run`'s status, enforcing optimistic concurrency:
    the row's CURRENT status must equal `expected_status` or this
    raises `ConcurrencyConflictError` — never a blind overwrite.
    `**fields` may set any other `Run` column atomically alongside the
    status change (e.g. `started_at`, `exit_code`, `failure_reason`).

    This is the ONLY repository function that changes `Run.status`;
    see `researchos.execution.runs` for the deterministic transition
    table and terminal-state immutability enforcement built on top of
    it (this function alone does not know which transitions are
    scientifically meaningful — only that the caller's expectation
    matched reality).
    """
    run = session.get(Run, run_id)
    if run is None:
        raise NotFoundError(f"Run {run_id} does not exist.")
    if run.status != expected_status:
        raise ConcurrencyConflictError(
            f"Run {run_id} expected status {expected_status.value!r} but was {run.status.value!r}."
        )
    run.status = new_status
    _apply_updates(run, fields)
    _flush(session)
    return run


