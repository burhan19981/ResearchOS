def create_analysis_input(
    session: Session, *, project_id: int, analysis_record_id: int, input_type: AnalysisInputType, input_id: int
) -> AnalysisInput:
    """Record one (input_type, input_id) edge. Validates that
    `analysis_record_id` and the polymorphic `(input_type, input_id)`
    both actually exist in this project before inserting — `input_id`
    cannot be a database foreign key since it points into different
    tables depending on `input_type` (same boundary as `EvidenceLink.
    subject_id` — see `_ANALYSIS_INPUT_MODELS`)."""
    _get_project_or_raise(session, project_id)
    record = session.get(AnalysisRecord, analysis_record_id)
    if record is None or record.project_id != project_id:
        raise NotFoundError(f"AnalysisRecord {analysis_record_id} does not exist in project {project_id}.")
    input_model = _ANALYSIS_INPUT_MODELS[input_type]
    input_row = session.get(input_model, input_id)
    if input_row is None or getattr(input_row, "project_id", None) != project_id:
        raise NotFoundError(f"{input_type.value} {input_id} does not exist in project {project_id}.")

    link = AnalysisInput(
        project_id=project_id, analysis_record_id=analysis_record_id, input_type=input_type, input_id=input_id,
    )
    session.add(link)
    _flush(session)
    return link


